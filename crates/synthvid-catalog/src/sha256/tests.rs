fn check_against_independent_oracle_boundary_lengths() -> Result<(), Fail> {
    for (len, expected) in VECTORS {
        let mut rng = synthvid_scene::Rng::from_seed(synthvid_scene::Seed::new(0x1234_5678));
        let byte_bound = synthvid_scene::DrawBound(NonZeroU64::new(256).or_fail()?);
        let mut input = vec![0_u8; len];
        for byte in &mut input {
            *byte = u8::try_from(rng.next_bounded(byte_bound).0).or_fail()?;
        }

        let result = sha256(&input);
        ensure_eq!(
            result.as_bytes(),
            &expected,
            "mismatch for input length {len}"
        );
    }
    Ok(())
}

#[test]
fn against_independent_oracle_boundary_lengths() {
    assert_eq!(check_against_independent_oracle_boundary_lengths(), Ok(()));
}

fn check_streaming_vs_oneshot() -> Result<(), Fail> {
    // Test that streaming with awkward chunk sizes produces the same result as one-shot.
    let seed = [
        0x12_u8, 0x34_u8, 0x56_u8, 0x78_u8, 0x9a_u8, 0xbc_u8, 0xde_u8, 0xf0_u8,
    ];
    let input: Vec<u8> = seed.iter().copied().cycle().take(300).collect();
    let oneshot_result = sha256(&input);

    // Hash with streaming in awkward chunk sizes: 1, then 63 (completing a
    // 64-byte block with the previous 1), then 64 (exactly one block), then
    // 65 (one block plus 1), then the rest in 127-byte chunks.
    let mut streaming = Sha256::new();
    let mut rest = input.as_slice();
    for size in [1_usize, 63, 64, 65] {
        let (chunk, tail) = rest.split_at_checked(size).or_fail()?;
        streaming.update(chunk);
        rest = tail;
    }
    for chunk in rest.chunks(127) {
        streaming.update(chunk);
    }

    let streaming_result = streaming.finalize();
    ensure_eq!(
        streaming_result.as_bytes(),
        oneshot_result.as_bytes(),
        "streaming interface produced different result than one-shot"
    );
    Ok(())
}

#[test]
fn streaming_vs_oneshot() {
    assert_eq!(check_streaming_vs_oneshot(), Ok(()));
}
